"""EIDOLON v1.0 (Agent A): MultiMesh variants of the repeated-quad shaders, generated from the originals so they
never drift: each per-material uniform becomes a flat varying filled from INSTANCE_CUSTOM / the instance COLOR.
  python3 eidolon-world/dev_rig/tools/make_mm_shaders.py      (re-run after editing an original)
The layout (which uniform sits in which slot) is mirrored in scripts/fx/quad_batch.gd (QuadBatch.LAYOUT).
"""
import os, re
D = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'shaders')
# shader -> [(uniform name, glsl type, source expression in vertex())]
LAYOUT = {
    'rune_face': [('design', 'float', 'INSTANCE_CUSTOM.r'), ('lit', 'float', 'INSTANCE_CUSTOM.g'),
                  ('flare', 'float', 'INSTANCE_CUSTOM.b'), ('hers', 'float', 'INSTANCE_CUSTOM.a'),
                  ('on_floor', 'float', 'COLOR.r'), ('numeral', 'float', 'COLOR.g * 4.0'), ('mirror', 'float', 'COLOR.b')],
    'floor_mark': [('kind', 'float', 'INSTANCE_CUSTOM.r'), ('intensity', 'float', 'INSTANCE_CUSTOM.g'),
                   ('sweep', 'float', 'INSTANCE_CUSTOM.b'), ('fill', 'float', 'INSTANCE_CUSTOM.a'),
                   ('joint', 'float', 'COLOR.r'), ('hers', 'float', 'COLOR.g')],
    'halo': [('color', 'vec3', 'COLOR.rgb'), ('intensity', 'float', 'INSTANCE_CUSTOM.r')],
    'light_pool': [('k', 'float', 'INSTANCE_CUSTOM.r')],
}
for name, slots in LAYOUT.items():
    src = open(os.path.join(D, name + '.gdshader')).read()
    s = src
    for u, ty, _ in slots:
        pat = re.compile(r'^uniform\s+' + ty + r'\s+' + u + r'\b[^;]*;.*$', re.M)
        assert pat.search(s), (name, u)
        s = pat.sub('varying flat %s %s;      // (MultiMesh: per instance)' % (ty, u), s, count=1)
    # helper functions that read a per-instance value become macros (functions cannot read varyings)
    for fn in re.findall(r'^vec3 (_h[act])\(\) \{ return .*; \}$', s, flags=re.M):
        s = re.sub(r'^vec3 ' + fn + r'\(\) \{ return (.*); \}$', lambda m_: '#define %s (%s)' % (fn.upper(), m_.group(1)), s, flags=re.M)
        s = s.replace(fn + '()', fn.upper())
    assign = '\n'.join('\t%s = %s;' % (u, e) for u, _, e in slots)
    if 'void vertex()' in s:
        s = s.replace('void vertex() {', 'void vertex() {\n' + assign, 1)
    else:
        s = s.replace('void fragment()', 'void vertex() {\n' + assign + '\n}\n\nvoid fragment()', 1)
    if name == 'halo':
        # the billboard keeps the instance's scale (one shared unit quad; each halo its own size)
        a = 'MODELVIEW_MATRIX = VIEW_MATRIX * mat4(INV_VIEW_MATRIX[0], INV_VIEW_MATRIX[1], INV_VIEW_MATRIX[2], MODEL_MATRIX[3]);'
        assert a in s
        s = s.replace(a, 'float s_ = length(MODEL_MATRIX[0].xyz);\n\tMODELVIEW_MATRIX = VIEW_MATRIX * mat4(INV_VIEW_MATRIX[0] * s_, INV_VIEW_MATRIX[1] * s_, INV_VIEW_MATRIX[2] * s_, MODEL_MATRIX[3]);')
    head = '// GENERATED by dev_rig/tools/make_mm_shaders.py from %s.gdshader: the MultiMesh variant (scripts/fx/quad_batch.gd).\n// Do not edit: edit the original and re-run the tool.\n' % name
    s = s.replace('shader_type spatial;\n', 'shader_type spatial;\n' + head, 1)
    open(os.path.join(D, name + '_mm.gdshader'), 'w').write(s)
    print('wrote', name + '_mm.gdshader')
